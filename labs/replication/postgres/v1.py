from __future__ import annotations

import json

from common import connect, scalar, wait_for


def setup() -> None:
    with connect("subscriber") as subscriber, connect("primary") as primary:
        subscriber.execute("DROP SUBSCRIPTION IF EXISTS r04_sub")
        primary.execute("DROP PUBLICATION IF EXISTS r04_pub")
        for conn in (primary, subscriber):
            conn.execute("DROP TABLE IF EXISTS orders")
            conn.execute("CREATE TABLE orders (id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, value text NOT NULL)")
        primary.execute("INSERT INTO orders(value) VALUES ('initial')")
        primary.execute("CREATE PUBLICATION r04_pub FOR TABLE orders")
        subscriber.execute("CREATE SUBSCRIPTION r04_sub CONNECTION 'host=primary port=5432 dbname=r04 user=r04 password=r04_local_only' PUBLICATION r04_pub")
        wait_for(lambda: subscriber.execute("SELECT id,value FROM orders ORDER BY id").fetchall() == [(1, "initial")], "initial table copy")


def experiment() -> dict[str, object]:
    setup()
    with connect("primary") as primary, connect("subscriber") as subscriber:
        primary.execute("DROP TABLE IF EXISTS unpublished")
        primary.execute("CREATE TABLE unpublished(id int)")
        primary.execute("INSERT INTO orders(value) VALUES ('inserted')")
        wait_for(lambda: subscriber.execute("SELECT id,value FROM orders ORDER BY id").fetchall() == [(1, "initial"), (2, "inserted")], "logical insert")
        primary.execute("UPDATE orders SET value='updated' WHERE id=2")
        wait_for(lambda: scalar(subscriber, "SELECT value FROM orders WHERE id=2") == "updated", "logical update")
        primary.execute("DELETE FROM orders WHERE id=1")
        wait_for(lambda: subscriber.execute("SELECT id,value FROM orders ORDER BY id").fetchall() == [(2, "updated")], "logical delete")
        assert scalar(subscriber, "SELECT to_regclass('public.unpublished')") is None
        return {"rows": [[2, "updated"]], "unpublished_absent": True, "operations": ["initial_copy", "insert", "update", "delete"]}


if __name__ == "__main__":
    print(json.dumps(experiment()))
